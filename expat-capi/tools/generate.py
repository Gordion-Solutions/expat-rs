#!/usr/bin/env python3
"""Generate expat-capi/src/generated.rs from libexpat's header and library.

Usage: generate.py [<libexpat prefix>]   (default: `brew --prefix expat`)

Compiles a small C program against expat-capi/include/expat.h (libexpat
2.7.1's header, shipped unchanged) to print enum values and struct layouts,
and links it against an installed libexpat to read XML_ErrorString for each
error code. libexpat is used as a black box here, as METHODOLOGY.md allows;
none of its source is read. Do not edit generated.rs by hand; rerun this.
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
INCLUDE = os.path.join(HERE, "..", "include")
OUT = os.path.join(HERE, "..", "src", "generated.rs")


def enum_members(header, enum):
    body = re.search(r"enum %s\s*\{(.*?)\};" % enum, header, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return [m.split("=")[0].strip() for m in body.split(",") if m.strip()]


def main():
    prefix = sys.argv[1] if len(sys.argv) > 1 else subprocess.run(
        ["brew", "--prefix", "expat"], capture_output=True, text=True, check=True).stdout.strip()
    header = open(os.path.join(INCLUDE, "expat.h")).read()
    errors = enum_members(header, "XML_Error")
    ctypes = enum_members(header, "XML_Content_Type")
    quants = enum_members(header, "XML_Content_Quant")
    features = enum_members(header, "XML_FeatureEnum")
    c = ['#include <stdio.h>', '#include <stddef.h>', '#include "expat.h"',
         'const XML_LChar *real_error_string(enum XML_Error);', 'int main(void) {']
    for group in (errors, ctypes, quants, features):
        for name in group:
            c.append(f'  printf("const {name} %ld\\n", (long){name});')
    for name in errors:
        c.append(f'  printf("str {name} %s\\n", real_error_string({name}) ? (const char *)real_error_string({name}) : "");')
    for t in ("XML_Content", "XML_Feature", "XML_Expat_Version", "XML_Encoding", "XML_Memory_Handling_Suite"):
        c.append(f'  printf("size {t} %zu\\n", sizeof({t}));')
    c += ['  return 0;', '}']
    # real_error_string calls the installed libexpat's XML_ErrorString; it is
    # compiled separately so that it uses that library's own declarations.
    shim = '#include <expat.h>\nconst XML_LChar *real_error_string(enum XML_Error e) { return XML_ErrorString(e); }\n'
    with tempfile.TemporaryDirectory() as d:
        open(f"{d}/main.c", "w").write("\n".join(c))
        open(f"{d}/real.c", "w").write(shim)
        subprocess.run(["cc", "-c", "-I", INCLUDE, "-o", f"{d}/main.o", f"{d}/main.c"], check=True)
        subprocess.run(["cc", "-c", "-I", f"{prefix}/include", "-o", f"{d}/real.o", f"{d}/real.c"], check=True)
        subprocess.run(["cc", "-o", f"{d}/gen", f"{d}/main.o", f"{d}/real.o", f"-L{prefix}/lib", "-lexpat"], check=True)
        out = subprocess.run([f"{d}/gen"], capture_output=True, text=True, check=True,
                             env={**os.environ, "DYLD_LIBRARY_PATH": f"{prefix}/lib", "LD_LIBRARY_PATH": f"{prefix}/lib"}).stdout
        version = subprocess.run(["sh", "-c", f"ls {prefix}/lib/libexpat.*.dylib {prefix}/lib/libexpat.so.* 2>/dev/null | head -1"],
                                 capture_output=True, text=True).stdout.strip()
    consts, strings, sizes = [], [], []
    for line in out.splitlines():
        kind, name, value = line.split(" ", 2)
        if kind == "const":
            consts.append((name, int(value)))
        elif kind == "str":
            strings.append((name, value))
        else:
            sizes.append((name, int(value)))
    rs = ["//! Constants from libexpat 2.7.1's expat.h and error strings from an",
          "//! installed libexpat's XML_ErrorString.",
          "//!",
          "//! GENERATED by tools/generate.py; do not edit by hand.",
          "#![allow(dead_code, non_upper_case_globals)]",
          ""]
    for name, value in consts:
        rs.append(f"pub const {name}: i32 = {value};")
    rs.append("")
    rs.append("/// XML_ErrorString text for each XML_Error code, indexed by code.")
    rs.append(f"pub static ERROR_STRINGS: [&[u8]; {len(strings)}] = [")
    for name, text in strings:
        rs.append(f"    b\"{text.replace(chr(92), chr(92)*2).replace(chr(34), chr(92)+chr(34))}\\0\", // {name}")
    rs.append("];")
    rs.append("")
    for name, value in sizes:
        rs.append(f"pub const SIZEOF_{name}: usize = {value};")
    open(OUT, "w").write("\n".join(rs) + "\n")
    print(f"wrote {OUT}: {len(consts)} constants, {len(strings)} error strings, {len(sizes)} sizes")


if __name__ == "__main__":
    main()
