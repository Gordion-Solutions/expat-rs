#!/usr/bin/env python3
"""Generate tests/error_kind_tests.rs from libexpat's verdicts on the corpus.

Usage: gen_error_tests.py <libexpat-errcodes-binary>
(errcodes.c built against libexpat; see README.md.) For each case in
error_corpus.py, records libexpat's error code, line and column; the test
checks expat-rs reports the matching ErrorKind at the same place.
"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from error_corpus import CASES, NS_CASES  # noqa: E402

# libexpat XML_Error code -> expat-rs ErrorKind.
KINDS = {
    2: "Syntax", 3: "NoElements", 4: "InvalidToken", 5: "UnclosedToken", 6: "PartialChar",
    7: "TagMismatch", 8: "DuplicateAttribute", 9: "JunkAfterDocElement", 10: "ParamEntityRef",
    11: "UndefinedEntity", 12: "RecursiveEntityRef", 13: "AsyncEntity", 14: "BadCharRef",
    15: "BinaryEntityRef", 16: "AttributeExternalEntityRef", 17: "MisplacedXmlPi",
    18: "UnknownEncoding", 19: "IncorrectEncoding", 20: "UnclosedCdataSection",
    21: "ExternalEntityHandling", 27: "UnboundPrefix", 28: "UndeclaringPrefix", 30: "XmlDecl",
    31: "TextDecl", 32: "PublicId", 38: "ReservedPrefixXml", 39: "ReservedPrefixXmlns",
    40: "ReservedNamespaceUri", 43: "AmplificationLimitBreach",
}

# Cases where expat-rs deliberately differs from libexpat, with the reason.
KNOWN_DIVERGENCES = {
    "xml decl bad version": "libexpat accepts any version number; XML 1.0 §2.8 [26] allows only 1.x",
}


def rust_bytes(data):
    return 'b"' + "".join(chr(b) if 32 <= b < 127 and chr(b) not in '"\\' else f"\\x{b:02x}" for b in data) + '"'


def main():
    errcodes = sys.argv[1]
    rows = []
    with tempfile.TemporaryDirectory() as d:
        for ns, cases in ((False, CASES), (True, NS_CASES)):
            for i, (name, data) in enumerate(cases.items()):
                path = os.path.join(d, f"{int(ns)}_{i:03}.xml")
                open(path, "wb").write(data)
                out = subprocess.run([errcodes, *(["-n"] if ns else []), path], capture_output=True, text=True, check=True).stdout
                _, code, _, line, col = out.rstrip("\n").split("\t")
                rows.append((name, data, ns, int(code), int(line), int(col)))
    lines = [
        "//! Errors against libexpat: each malformed input must produce the",
        "//! ErrorKind matching the error code libexpat 2.8.2 reports for it, at",
        "//! the same line and column.",
        "//!",
        "//! GENERATED by capi/phase1/gen_error_tests.py from error_corpus.py and",
        "//! libexpat's output; do not edit by hand. Known divergences are listed",
        "//! in KNOWN_DIVERGENCES with a reason.",
        "",
        "use expat_rs::{decode, ErrorKind, Parser, StreamParser, XmlError};",
        "",
        "/// (case, input, namespace processing, libexpat's error as an ErrorKind",
        "/// (`None`: well-formed), line, column (0-based, as libexpat counts))",
        "type Case = (&'static str, &'static [u8], bool, Option<ErrorKind>, u32, u32);",
        "",
        "const CASES: &[Case] = &[",
    ]
    for name, data, ns, code, line, col in rows:
        kind = "None" if code == 0 else f"Some(ErrorKind::{KINDS[code]})"
        lines.append(f'    ("{name}", {rust_bytes(data)}, {str(ns).lower()}, {kind}, {line}, {col}),')
    lines += [
        "];",
        "",
        "/// Cases where expat-rs deliberately differs from libexpat.",
        "const KNOWN_DIVERGENCES: &[(&str, &str)] = &[",
        *[f'    ("{n}", "{r}"),' for n, r in KNOWN_DIVERGENCES.items()],
        "];",
        "",
        "fn error_of(input: &[u8], namespaces: bool) -> Option<XmlError> {",
        "    let result = (|| -> Result<(), XmlError> {",
        "        let text = decode(input)?;",
        "        let mut p = Parser::new(&text);",
        "        if namespaces { p = p.with_namespaces(); }",
        "        while p.next_event()?.is_some() {}",
        "        Ok(())",
        "    })();",
        "    result.err()",
        "}",
        "",
        "/// The same through the streaming parser, fed `chunk` bytes at a time.",
        "fn stream_error_of(input: &[u8], namespaces: bool, chunk: usize) -> Option<XmlError> {",
        "    let mut p = StreamParser::new();",
        "    if namespaces { p = p.with_namespaces(); }",
        "    for c in input.chunks(chunk) {",
        "        if let Err(e) = p.feed(c, |_| {}) { return Some(e); }",
        "    }",
        "    p.finish(|_| {}).err()",
        "}",
        "",
        "#[test]",
        "fn errors_match_libexpat() {",
        "    check(error_of);",
        "}",
        "",
        "#[test]",
        "fn stream_errors_match_libexpat() {",
        "    check(|input, ns| stream_error_of(input, ns, usize::MAX));",
        "    check(|input, ns| stream_error_of(input, ns, 1));",
        "}",
        "",
        "fn check(error_of: impl Fn(&[u8], bool) -> Option<XmlError>) {",
        "    let mut mismatches = Vec::new();",
        "    for &(name, input, ns, want, line, col) in CASES {",
        "        if KNOWN_DIVERGENCES.iter().any(|(n, _)| *n == name) { continue; }",
        "        let got = error_of(input, ns);",
        "        let got_kind = got.as_ref().map(XmlError::kind);",
        "        if got_kind != want {",
        "            mismatches.push(format!(\"{name}: libexpat {want:?}, expat-rs {got_kind:?}\"));",
        "        } else if let Some(e) = got {",
        "            let pos = e.position();",
        "            // expat-rs columns are 1-based.",
        "            if (pos.line, pos.column - 1) != (line, col) {",
        "                mismatches.push(format!(\"{name}: libexpat at {line}:{col}, expat-rs at {}:{} ({e})\", pos.line, pos.column - 1));",
        "            }",
        "        }",
        "    }",
        "    assert!(mismatches.is_empty(), \"{} mismatches:\\n{}\", mismatches.len(), mismatches.join(\"\\n\"));",
        "}",
    ]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tests", "error_kind_tests.rs")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {len(rows)} cases to {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
